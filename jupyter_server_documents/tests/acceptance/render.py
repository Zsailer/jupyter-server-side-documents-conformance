"""Generate SCENARIOS.md, CATALOGUE.md and STORYBOARDS.html from ``suite.yaml``, the scenario modules, ``recorded.json`` and ``storyboards/``.

    python -m jupyter_server_documents.tests.acceptance.render           # write the three documents
    python -m jupyter_server_documents.tests.acceptance.render --check   # exit 1 if they are out of date

Nothing in them is typed by hand, except the pictures of ``storyboards/``: change ``suite.yaml`` (or record new measurements
with ``export_recorded.py``, or edit a storyboard) and run this. The tables of CATALOGUE.md judge the recorded measurements
against the CURRENT clauses of ``suite.yaml``, so a change of policy shows at once across every version that was measured.
STORYBOARDS.html is about the product and knows nothing of versions: it is a page for a design review (see ``storyboard.py``).
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from . import storyboard
from . import suite as suite_mod
from .outcomes import describe
from .suite import describe_clause, evaluate

HERE = Path(__file__).resolve().parent
SCENARIOS_MD = HERE / "SCENARIOS.md"
CATALOGUE_MD = HERE / "CATALOGUE.md"
RECORDED = HERE / "recorded.json"
COMMAND = "python -m jupyter_server_documents.tests.acceptance.render"

MARK = {"reference": "ok", "floor": "gap", "none": "BAD"}


def _cell(text: str) -> str:
    return " ".join(str(text).split()).replace("|", "\\|")


def _clauses(clauses: tuple[dict, ...]) -> str:
    return "; ".join(f"`{describe_clause(c)}`" for c in clauses)


def scenarios_md(suite: suite_mod.Suite) -> str:
    pending = [s for s in suite.scenarios.values() if s.pending]
    best = [s for s in suite.scenarios.values() if s.best_effort]
    out = [
        "# Scenarios",
        "",
        f"Generated by `{COMMAND}` from `suite.yaml` and the scenario modules in `scenarios/`. Do not edit.",
        "",
        f"{len(suite.scenarios)} stories of a browser tab and a server room, played with the real room code of the checkout and the real client "
        "sync code. For each, `suite.yaml` says how it must end (the **reference**), the least it may fall to (the **floor**: nothing "
        "that must never happen did), what each kind of tree is expected to reach today, and whether the answer is decided. "
        f"{len(best)} answers are a best effort that can be changed and {len(pending)} wait for a decision.",
        "",
        "| Group | Scenarios |",
        "|---|---|",
    ]
    for gid, title in suite.groups.items():
        ids = [s.id for s in suite.scenarios.values() if s.group == gid]
        out.append(f"| {_cell(title)} | {' '.join(ids)} |")
    if best:
        out += [
            "",
            "## Decisions taken as a best effort",
            "",
            "Enforced like any other, and open to change: edit `reference`, `floor`, `expect` and `policy.decision` of the scenario in `suite.yaml`. "
            "The rule of thumb they follow is in the comment at the top of that file.",
            "",
        ]
        out += [f"- **{s.id}**: {_cell(s.policy.decision)}" for s in best]
    if pending:
        out += ["", "## Waiting for a decision", ""]
        out += [f"- **{s.id}**: {_cell(s.policy.question)}" for s in pending]
    for gid, title in suite.groups.items():
        members = [s for s in suite.scenarios.values() if s.group == gid]
        out += ["", f"## {title}", "", "| ID | Scenario | Must end with | Needs | Policy |", "|---|---|---|---|---|"]
        for s in members:
            story_title, _ = suite.story(s.id)
            needs = ", ".join(sorted(s.requires)) or "-"
            policy = "**pending**" if s.pending else ("best effort" if s.best_effort else "decided")
            out.append(f"| {s.id} | {_cell(story_title)} | {_cell(s.says)} | {needs} | {policy} |")
        for s in members:
            story_title, story = suite.story(s.id)
            out += ["", f"### {s.id}: {story_title}", "", story, ""]
            out.append(f"- **Must end with:** {_cell(s.says)}")
            out.append(f"- **Reference:** {_clauses(s.reference)}")
            if s.floor != s.reference:
                out.append(f"- **Floor:** {_clauses(s.floor)}")
            if s.requires:
                out.append(f"- **Needs:** {', '.join(sorted(s.requires))} (n/a on a tree without it)")
            if s.pending:
                out.append(f"- **Policy pending:** {_cell(s.policy.question)}")
                if s.policy.today:
                    out.append(f"  - Today: {_cell(s.policy.today)}")
            elif s.best_effort:
                out.append(f"- **Decision (best effort, open to change):** {_cell(s.policy.decision)}")
                if s.policy.question:
                    out.append(f"  - The question: {_cell(s.policy.question)}")
                if s.policy.today:
                    out.append(f"  - Today: {_cell(s.policy.today)}")
            for pname, e in s.expect.items():
                out.append(f"- **Expected on `{pname}`:** {e.level}" + (f". {_cell(e.why)}" if e.why else ""))
            out.append(f"- Module: `scenarios/{s.module}.py`")
    return "\n".join(out) + "\n"


def _profile_mark(s: suite_mod.Scenario, profile: suite_mod.Profile) -> str:
    e = s.expected(profile)
    if e.level == "n/a":
        return "n/a"
    if s.pending and e.level == "reference":
        return "?"
    return {"reference": "ok", "floor": "gap", "none": "BAD"}[e.level]


def catalogue_md(suite: suite_mod.Suite, recorded: dict) -> str:
    profiles = list(suite.profiles.values())
    versions = recorded["variants"]
    out = [
        "# Catalogue",
        "",
        f"Generated by `{COMMAND}` from `suite.yaml` and `recorded.json`. Do not edit.",
        "",
        "## What each kind of tree is expected to do",
        "",
        "A tree has the features it has (found in the checkout); `suite.yaml` says which level a scenario reaches on each kind of tree. "
        "`ok` meets the reference; `gap` is a known gap (it reaches the floor and no more); `?` waits for a policy decision; `n/a` needs "
        "a feature the kind of tree lacks.",
        "",
    ]
    out += [f"- **{p.name}**: {_cell(p.about)}" for p in profiles]
    out += ["", "| ID | Scenario | " + " | ".join(p.name for p in profiles) + " |", "|---|---|" + "---|" * len(profiles)]
    for s in suite.scenarios.values():
        title, _ = suite.story(s.id)
        out.append(f"| {s.id} | {_cell(title)} | " + " | ".join(_profile_mark(s, p) for p in profiles) + " |")
    totals = []
    for p in profiles:
        marks = [_profile_mark(s, p) for s in suite.scenarios.values()]
        totals.append(f"{marks.count('ok')} ok, {marks.count('gap')} gap, {marks.count('?')} ?, {marks.count('n/a')} n/a")
    out.append("| | **Totals** | " + " | ".join(totals) + " |")

    out += [
        "",
        "## What was measured, version by version",
        "",
        "The exploration kit (`repro/issue-70-divergent-sync`, PR #72) builds versions of the code and plays the scenarios against each; "
        "`recorded.json` holds what it saw. Each cell is a one-line reading of the verdict, judged against the clauses of `suite.yaml` as they "
        "are now: `ok` meets the reference, `gap` reaches only the floor, `BAD` falls below it, `?` is a scenario whose policy is pending "
        "and whose provisional reference is not met, `n/a` could not be played there and `-` was not measured.",
        "",
    ]
    out += [f"- **{v['column']}** (`{name}`): {_cell(v['about'])}" + (f". The measurement of a `{v['profile']}` tree." if v.get("profile") else "") for name, v in versions.items()]
    out += ["", "| ID | Scenario | " + " | ".join(v["column"] for v in versions.values()) + " |", "|---|---|" + "---|" * len(versions)]
    tally = {name: {"ok": 0, "gap": 0, "BAD": 0, "?": 0, "n/a": 0, "-": 0} for name in versions}
    for s in suite.scenarios.values():
        title, _ = suite.story(s.id)
        cells = []
        for name, v in versions.items():
            if s.id not in v["scenarios"]:
                mark, text = "-", "-"
            elif v["scenarios"][s.id] is None:
                mark, text = "n/a", "n/a"
            else:
                verdict = v["scenarios"][s.id]
                level = evaluate(s, verdict).level
                mark = "?" if (s.pending and level != "reference") else MARK[level]
                text = f"`{mark}` {_cell(describe(s.id, verdict))}"
            tally[name][mark] += 1
            cells.append(text)
        out.append(f"| {s.id} | {_cell(title)} | " + " | ".join(cells) + " |")
    out.append(
        "| | **Totals** | "
        + " | ".join(f"{t['ok']} ok, {t['gap']} gap, {t['BAD']} BAD, {t['?']} ?" for t in tally.values())
        + " |"
    )
    return "\n".join(out) + "\n"


def render_all() -> dict[Path, str]:
    suite = suite_mod.get()
    recorded = json.loads(RECORDED.read_text())
    return {
        SCENARIOS_MD: scenarios_md(suite),
        CATALOGUE_MD: catalogue_md(suite, recorded),
        storyboard.STORYBOARDS_HTML: storyboard.render_page(suite),
    }


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="do not write; exit 1 if a document is out of date")
    args = ap.parse_args(argv)
    stale = []
    for path, text in render_all().items():
        if args.check:
            if not path.exists() or path.read_text() != text:
                stale.append(path.name)
        else:
            path.write_text(text)
            print(f"wrote {path.relative_to(HERE.parent.parent.parent)}")
    if stale:
        print(f"out of date: {', '.join(stale)}. Run `{COMMAND}` and commit the result.", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
